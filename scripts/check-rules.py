#!/usr/bin/env python3
"""PostToolUse gate: rejects C# that breaks the plugin's conventions (rules/).

Reads the Write/Edit hook payload on stdin, re-reads the written file, and compares it to
its committed version so only *newly introduced* violations block — touching a legacy file
never traps the agent in someone else's debt.

Exit 2 + stderr  -> the model (main session or subagent) must fix it before moving on.
Exit 0 + JSON    -> advisory notes only.
"""

import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import asf_config  # noqa: E402

RULES_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "rules")

SKIP_PATH = re.compile(r"[/\\](obj|bin|Migrations)[/\\]|\.(g|Designer|generated)\.cs$", re.IGNORECASE)
TEST_PATH = re.compile(r"\.Tests?\b|[/\\]Tests?[/\\]|Tests\.cs$", re.IGNORECASE)

TYPE_DECL = re.compile(
    r"^(?P<indent>[ ]*)(?:(?:public|internal|private|protected|sealed|abstract|static|partial|file|ref|readonly|unsafe|new)\s+)*"
    r"(?P<kind>class|interface|record|struct|enum)\b(?:\s+(?:class|struct))?\s+(?P<name>[A-Za-z_]\w*)"
)
PRIMARY_CTOR = re.compile(
    r"^[ ]*(?:(?:public|internal|private|protected|sealed|abstract|static|partial|file)\s+)*"
    r"class\s+(?P<name>[A-Za-z_]\w*)(?:<[^>]*>)?\s*\((?P<params>[^)]*)\)"
)
DI_PARAM = re.compile(r"\bI[A-Z]\w*(?:<[^>]*>)?\s+\w+|\b\w*(?:Logger|Repository|Service|Client|Factory|Provider|Publisher|Mediator)(?:<[^>]*>)?\s+\w+")
ARTEFACT_COMMENT = re.compile(
    r"^\s*//.*?\b(task\s+\d+|per the (brief|plan|spec)|see\s+[\w./-]+\.md|implementation-plan)",
    re.IGNORECASE,
)
# The exhaustive exception list from code-convention.md § Comments.
ALLOWED_COMMENT = re.compile(
    r"^///|^//\s*(Arrange|Act|Assert)(\s*(&|,|and)\s*(Arrange|Act|Assert))*\s*$"
    r"|https?://\S+/browse/\S+|#pragma|^//\s*<auto-generated",
    re.IGNORECASE,
)
STRING_LITERAL = re.compile(r"@?\"(?:[^\"\\]|\\.)*\"|'(?:[^'\\]|\\.)'")

# (rule id, pattern, message, blocking)
LINE_RULES = [
    ("no-ioptions", re.compile(r"\bIOptions<"),
     "IOptions<T> is banned — use IOptionsSnapshot<T> (scoped) or IOptionsMonitor<T> (singleton).", True),
    ("no-sync-over-async", re.compile(r"\.Wait\(\)|\.GetAwaiter\(\)\.GetResult\(\)"),
     "Blocking on a Task — await it instead (common.md § Prohibitions).", True),
    ("no-async-void", re.compile(r"\basync\s+void\b"),
     "async void — return Task so the caller can observe completion.", True),
    ("no-datetime-now", re.compile(r"\bDateTime(Offset)?\.Now\b"),
     "DateTime.Now — inject a time provider (common.md § Prohibitions).", True),
    ("no-moq", re.compile(r"\busing\s+Moq\b|\bnew\s+Mock<|\bIt\.Is(Any)?<"),
     "Moq is banned — use NSubstitute (test-convention.md).", True),
    ("no-null-guard", re.compile(r"\?\?\s*throw\s+new\s+ArgumentNullException"),
     "No ArgumentNullException guards for injected services — assign directly.", False),
    ("no-arg-do", re.compile(r"\bArg\.Do<"),
     "Arg.Do captures parameters — constrain the input with Arg.Is<T>(...) instead.", False),
    ("no-task-fromresult-stub", re.compile(r"\.Returns\(\s*Task\.FromResult\("),
     "NSubstitute auto-wraps async returns — use .Returns(value).", False),
    ("prefer-init", re.compile(r"\{\s*get;\s*set;\s*\}"),
     "New properties use { get; init; } (code-convention.md § Properties).", False),
]

CSPROJ_RULES = [
    ("fluentassertions-v7", re.compile(r'Include="FluentAssertions"[^>]*Version="(?!7\.)', re.IGNORECASE),
     "FluentAssertions must stay pinned at 7.2.0 — v8+ is commercially licensed.", True),
    ("no-moq", re.compile(r'Include="Moq"', re.IGNORECASE),
     "Moq is banned — use NSubstitute.", True),
]


def hook_file_path(payload):
    for source, key in (("tool_response", "filePath"), ("tool_input", "file_path"), ("inputs", "file_path")):
        block = payload.get(source)
        if isinstance(block, dict) and block.get(key):
            return block[key]
    return None


def baseline(path):
    """The file's committed content, or None when it is new or untracked."""
    repo = os.path.dirname(os.path.abspath(path))
    try:
        root = subprocess.run(["git", "-C", repo, "rev-parse", "--show-toplevel"],
                              capture_output=True, text=True, timeout=10)
        if root.returncode != 0:
            return None
        rel = os.path.relpath(os.path.abspath(path), root.stdout.strip())
        show = subprocess.run(["git", "-C", repo, "show", f"HEAD:{rel}"],
                              capture_output=True, text=True, timeout=10)
        return show.stdout if show.returncode == 0 else None
    except (OSError, subprocess.SubprocessError):
        return None


def code_lines(text):
    """Line-numbered source with comment-only and using lines dropped."""
    for number, line in enumerate(text.splitlines(), start=1):
        stripped = line.lstrip()
        if stripped.startswith(("//", "*", "/*")):
            continue
        yield number, line.replace("\t", "    ")


def top_level_types(text):
    base = 0 if re.search(r"^namespace\s+[\w.]+\s*;", text, re.MULTILINE) else 4
    found = []
    for number, line in code_lines(text):
        match = TYPE_DECL.match(line)
        if match and len(match.group("indent")) == base:
            found.append((number, match.group("name")))
    return found


def body_comments(text):
    """Line numbers of `//` and `/* */` comments sitting inside a member body."""
    body = 2 if re.search(r"^namespace\s+[\w.]+\s*;", text, re.MULTILINE) else 3
    raw_lines = text.splitlines()
    depth, in_block = 0, False
    for number, raw in enumerate(raw_lines, start=1):
        line = STRING_LITERAL.sub('""', raw)
        if in_block:
            in_block = "*/" not in line
            continue
        stripped = line.strip()
        if stripped.startswith("/*"):
            in_block = "*/" not in stripped
            if depth >= body:
                yield number
            continue
        start = line.find("//")
        if start == -1:
            depth += line.count("{") - line.count("}")
            continue
        following = raw_lines[number] if number < len(raw_lines) else ""
        if (depth >= body
                and not ALLOWED_COMMENT.search(line[start:].strip())
                and "#pragma" not in following):
            yield number
        code = line[:start]
        depth += code.count("{") - code.count("}")


XML_TAG = re.compile(r"<[^>]+>")
XML_DOC_MAX_PROSE_LINES = 4


def long_xml_docs(text):
    """Start line and prose length of every /// block whose prose runs past the budget."""
    start, prose = None, 0
    for number, raw in enumerate(text.splitlines() + [""], start=1):
        stripped = raw.strip()
        if stripped.startswith("///"):
            start = start or number
            if XML_TAG.sub("", stripped[3:]).strip():
                prose += 1
            continue
        if start and prose > XML_DOC_MAX_PROSE_LINES:
            yield start, prose
        start, prose = None, 0


def inspect(path, text):
    """Returns (blocking, advisory) violations as (rule_id, line, message) tuples."""
    blocking, advisory = [], []
    is_test = bool(TEST_PATH.search(path))

    if path.endswith(".csproj"):
        for number, line in enumerate(text.splitlines(), start=1):
            for rule, pattern, message, blocks in CSPROJ_RULES:
                if pattern.search(line):
                    (blocking if blocks else advisory).append((rule, number, message))
        return blocking, advisory

    types = top_level_types(text)
    if len(types) > 1:
        names = ", ".join(name for _, name in types)
        blocking.append(("single-type-per-file", types[1][0],
                         f"{len(types)} top-level types in one file ({names}) — split them, one per file."))
    elif types:
        expected = os.path.basename(path)[:-3]
        if types[0][1] != expected and "partial" not in text:
            blocking.append(("filename-parity", types[0][0],
                             f"Type '{types[0][1]}' must live in {types[0][1]}.cs, not {os.path.basename(path)}."))

    for number, line in code_lines(text):
        primary = PRIMARY_CTOR.match(line)
        if primary and primary.group("params").strip() and DI_PARAM.search(primary.group("params")):
            blocking.append(("no-primary-ctor", number,
                             f"Primary constructor on DI-resolved class '{primary.group('name')}' — "
                             "use an explicit ctor with private readonly _fields."))
        for rule, pattern, message, blocks in LINE_RULES:
            if rule == "no-moq" and not is_test:
                continue
            if rule == "no-ioptions" and is_test:
                continue
            if rule == "prefer-init" and "record" in line:
                continue
            if rule == "no-ioptions" and re.search(
                    r"IOptions(Snapshot|Monitor|Factory|MonitorCache|ChangeTokenSource)<"
                    r"|I(Configure|PostConfigure|Validate)Options<", line):
                continue
            if pattern.search(line):
                (blocking if blocks else advisory).append((rule, number, message))

    for number, line in enumerate(text.splitlines(), start=1):
        if ARTEFACT_COMMENT.match(line):
            blocking.append(("no-artefact-comments", number,
                             "Comment references a task/plan artefact — state what is true, not what produced it."))

    for number in body_comments(text):
        blocking.append(("no-inline-comments", number,
                         "Comment inside a method body — extract the block into a method named for "
                         "what the comment said and put the explanation in /// XML doc on it."))

    for number, prose in long_xml_docs(text):
        advisory.append(("xmldoc-brevity", number,
                         f"XML doc runs {prose} lines of prose — keep it to the main idea "
                         "(1–2 lines); move rationale to docs/."))

    if is_test and re.search(r"\bAssert\.\w+\(", text):
        advisory.append(("fluentassertions", 0, "Bare xUnit Assert — use FluentAssertions (.Should()...)."))

    return blocking, advisory


def keys(violations):
    return {(rule, message) for rule, _, message in violations}


def apply_config(path, blocking, advisory):
    """Re-tiers violations per `.claude/agentic-sdd-flow.json` → checks: {id: block|advisory|off}."""
    cfg = asf_config.load_config(asf_config.find_project_root(os.path.dirname(path)))
    levels = {k: str(v).lower() for k, v in (cfg.get("checks") or {}).items()}
    if not levels:
        return blocking, advisory
    kept_blocking, kept_advisory = [], []
    for item in blocking + advisory:
        level = levels.get(item[0], "block" if item in blocking else "advisory")
        if level == "off":
            continue
        (kept_blocking if level == "block" else kept_advisory).append(item)
    return kept_blocking, kept_advisory


def main():
    try:
        payload = json.load(sys.stdin)
    except (json.JSONDecodeError, ValueError):
        return 0

    path = hook_file_path(payload)
    if not path or not path.endswith((".cs", ".csproj")) or SKIP_PATH.search(path):
        return 0
    if not os.path.exists(path):
        return 0

    try:
        with open(path, encoding="utf-8-sig") as handle:
            text = handle.read()
    except OSError:
        return 0

    blocking, advisory = inspect(path, text)
    blocking, advisory = apply_config(path, blocking, advisory)
    if not blocking and not advisory:
        return 0

    old = baseline(path)
    if old is not None:
        was_blocking, was_advisory = inspect(path, old)
        was_blocking, was_advisory = apply_config(path, was_blocking, was_advisory)
        blocking = [v for v in blocking if (v[0], v[2]) not in keys(was_blocking)]
        advisory = [v for v in advisory if (v[0], v[2]) not in keys(was_advisory)]

    if not blocking and not advisory:
        return 0

    name = os.path.basename(path)
    if blocking:
        lines = [f"🔴 Convention violations in {name} — fix before continuing:", ""]
        lines += [f"  {name}:{number}  [{rule}] {message}" for rule, number, message in blocking]
        if advisory:
            lines += ["", "  Also worth fixing:"]
            lines += [f"  {name}:{number}  [{rule}] {message}" for rule, number, message in advisory]
        lines += ["", "These conventions are project law. They outrank the plan and any skill;",
                  f"read {RULES_DIR}/RULES-CONTRACT.md if a rule is unclear."]
        sys.stderr.write("\n".join(lines) + "\n")
        return 2

    notes = "; ".join(f"{name}:{number} [{rule}] {message}" for rule, number, message in advisory)
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "PostToolUse",
        "additionalContext": f"Conventions — advisory on {name}: {notes}",
    }}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
